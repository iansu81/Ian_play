/* Example 1:

Input: triangle = [[2],[3,4],[6,5,7],[4,1,8,3]]
Output: 11
Explanation: The triangle looks like:
   2
  3 4
 6 5 7
4 1 8 3
The minimum path sum from top to bottom is 2 + 3 + 5 + 1 = 11 (underlined above).
*/

class Solution {
public:
    int minimumTotal(vector<vector<int>>& triangle) {
        /**********************************************************************
         * 為什麼要從底部向上？
         * --------------------------------------------------------------------
         * 因為每一個位置 triangle[i][j] 的最小路徑，是由下一層的兩個位置決定：
         *
         *     (i, j) → (i+1, j)
         *      或     → (i+1, j+1)
         *
         * 也就是說，我們必須「知道下一層（i+1）所有位置的最小路徑和」，
         * 才能算出目前這層（i）的最小路徑和。
         *
         * 若從上往下算，路徑會有分支，我們無法只用 O(n) 空間保存所有可能的路徑。
         * 但從底往上算，每一層都只依賴「下一層」→ 所以可以覆寫、減少空間。
         *
         *
         * 為什麼這樣可以做到 O(n) 空間？
         * --------------------------------------------------------------------
         * dp 的長度 = 最底層元素數量 = triangle 高度 = n
         *
         * 我們從最底層開始，逐層往上覆寫 dp：
         *    - 第 i 層只需要下一層的資料（存於 dp）
         *    - 每次更新時直接覆寫 dp[j]
         *
         * 所以我們根本不需要 2D DP 表，只需要 1D 長度 = n 的 dp 陣列。
         *
         *
         * transition function 解釋（重點中的重點）
         * --------------------------------------------------------------------
         * dp[j] = triangle[i][j] + min(dp[j], dp[j + 1])
         *
         * 這行做的事情是：
         *  1. triangle[i][j] 是目前位置的值
         *  2. dp[j]     = 下一層 (i+1, j) 的最小路徑和（上一輪已算好）
         *     dp[j+1]   = 下一層 (i+1, j+1) 的最小路徑和
         *  3. 從下一層兩條可走路徑取最小
         *
         * 因為我們是從底往上，所以 dp[j] 舊的內容就是「下一層的結果」。
         **********************************************************************/

        // 初始化 dp：使用最底層資料作為「已知的最小路徑和」
        // 底層本身的最小路徑就是該格本身，不需要再往下走。
        vector<int> dp = triangle.back();

        // 從倒數第二層開始往上走（index = triangle.size()-2）
        // 直到 index = 0（頂部）
        for(int i = (int)triangle.size() - 2; i >= 0; i--) {

            // 每層有 i+1 個元素，因此 j = 0 ~ i
            for(int j = 0; j <= i; j++) {

                // transition:
                // 從 (i+1, j) 和 (i+1, j+1) 選一個較小的，下加上目前 triangle[i][j]
                // dp[j] 舊值：下一層位置 (i+1, j)
                // dp[j+1]   ：下一層位置 (i+1, j+1)
                // 更新後 dp[j] 代表：從 (i, j) 到最底層的最小路徑和
                dp[j] = triangle[i][j] + min(dp[j], dp[j+1]);
            }
        }

        // dp[0] 最後即為從頂部 (0,0) 走到底的最小路徑和
        return dp[0];
    }
};
